import { writeFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import { CITY_COURSES } from '../src/track/cityCourseData';
import { generateCityCourses } from '../src/track/cityCourseGen';
import { TrackPath } from '../src/track/TrackPath';
import { SCENES } from '../src/world/scenes';
import { cityStreets } from '../src/world/World';

/**
 * The city courses are traced along the free drive city's streets. Run with GEN=1 to write them
 * into src/track/cityCourseData.ts after changing the streets.
 */
describe('city courses', () => {
  const fresh = generateCityCourses();

  it('match the free drive city (regenerate with GEN=1 if the streets changed)', () => {
    if (process.env.GEN) {
      const file = new URL('../src/track/cityCourseData.ts', import.meta.url);
      const head = `import type { CityCourseId } from '../../shared/api';
import type { TrackLayout } from './TrackPath';

/** A street circuit through the free drive city (generated: see cityCourseGen.ts). */
export interface CityCourseData {
  id: CityCourseId;
  layout: TrackLayout;
  /** Checkpoint gates (lap distances): rejoining the course past one you skipped doesn't count. */
  gates: number[];
  /** Official shortcuts down side streets: where they leave and rejoin the course, and their line. */
  shortcuts: { from: number; to: number; pts: [number, number][] }[];
}

// Generated by \`GEN=1 npx vitest run tests/cityCourses.test.ts\` - don't edit by hand.
export const CITY_COURSES: CityCourseData[] = ${JSON.stringify(fresh)};
`;
      writeFileSync(file, head);
      return;
    }
    expect(JSON.stringify(CITY_COURSES)).toBe(JSON.stringify(fresh));
  });

  it.each(fresh.map((c) => [c.id, c] as const))('%s is a sensible street circuit', (_id, course) => {
    const track = new TrackPath(course.layout);
    expect(track.length).toBeGreaterThan(1500);
    expect(track.length).toBeLessThan(4000);
    expect(course.gates.length).toBeGreaterThan(6);
    expect(course.shortcuts.length).toBeGreaterThanOrEqual(1);
    for (const s of course.shortcuts) expect(s.pts.length).toBeGreaterThan(5);
    // The course runs down the middle of the streets (a little inside at the junctions).
    const scene = SCENES.freeroam;
    if (scene.kind !== 'rural' || !scene.city) throw new Error('no city');
    const streets = cityStreets(scene.cityRadius!, scene.city).streets.slice(0, 11);
    let worst = 0;
    for (const p of track.samples) {
      let best = Infinity;
      for (const s of streets) {
        for (let i = 1; i < s.pts.length; i++) best = Math.min(best, segDist(p.x, p.z, s.pts[i - 1], s.pts[i]));
      }
      worst = Math.max(worst, best);
    }
    expect(worst).toBeLessThan(7);
  });
});

function segDist(x: number, z: number, a: [number, number], b: [number, number]): number {
  const dx = b[0] - a[0];
  const dz = b[1] - a[1];
  const t = Math.max(0, Math.min(1, ((x - a[0]) * dx + (z - a[1]) * dz) / (dx * dx + dz * dz || 1)));
  return Math.hypot(x - a[0] - dx * t, z - a[1] - dz * t);
}
